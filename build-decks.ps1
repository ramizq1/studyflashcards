# Rebuilds data.js from courses/courses.json and every deck JSON file under notes/.
# Run this (or double-click update-decks.bat) whenever you add, edit, or remove a deck or course.
$ErrorActionPreference = 'Stop'

$root        = Split-Path -Parent $MyInvocation.MyCommand.Path
$coursesPath = Join-Path $root 'courses\courses.json'
$notesDir    = Join-Path $root 'notes'
$outPath     = Join-Path $root 'data.js'
$utf8        = New-Object System.Text.UTF8Encoding $false

function Read-JsonText([string]$path) {
    $text = [System.IO.File]::ReadAllText($path, [System.Text.Encoding]::UTF8).Trim()
    $obj  = $text | ConvertFrom-Json   # throws if the JSON is invalid
    return @{ Text = $text; Obj = $obj }
}

if (-not (Test-Path $coursesPath)) { throw "Missing $coursesPath" }
$courses = Read-JsonText $coursesPath
Write-Host "Courses: $(@($courses.Obj.courses).Count) listed in courses\courses.json"

$entries = New-Object System.Collections.Generic.List[string]
$skipped = 0
if (Test-Path $notesDir) {
    Get-ChildItem -Path $notesDir -Filter *.json -Recurse | Sort-Object FullName | ForEach-Object {
        $rel = $_.FullName.Substring($notesDir.Length + 1).Replace('\', '/')
        try {
            $deck = Read-JsonText $_.FullName
            if (-not $deck.Obj.course -or -not $deck.Obj.questions) {
                throw 'needs "course" and "questions" fields'
            }
            $file = $rel.Replace('"', '\"')
            $entries.Add("    { ""file"": ""$file"", ""data"": $($deck.Text) }")
            Write-Host ("  OK    {0}  ({1} questions)" -f $rel, @($deck.Obj.questions).Count) -ForegroundColor Green
        } catch {
            $skipped++
            Write-Host ("  SKIP  {0}: {1}" -f $rel, $_.Exception.Message) -ForegroundColor Yellow
        }
    }
}

$stamp = (Get-Date).ToString('yyyy-MM-ddTHH:mm:ss')
$js = "// AUTO-GENERATED by build-decks.ps1 on $stamp. Do not edit by hand; edit notes/ and courses/ instead.`n" +
      "window.FLASHCARDS = {`n" +
      "  ""generated"": ""$stamp"",`n" +
      "  ""courses"": $($courses.Text),`n" +
      "  ""decks"": [`n" + ($entries -join ",`n") + "`n  ]`n};`n"

[System.IO.File]::WriteAllText($outPath, $js, $utf8)
Write-Host ""
Write-Host "Built data.js with $($entries.Count) deck(s)." -ForegroundColor Cyan
if ($skipped) { Write-Host "$skipped file(s) skipped; fix them and run again." -ForegroundColor Yellow }
